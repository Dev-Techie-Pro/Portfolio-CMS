export function resolvePublicIconKey(key: string) {
  const trimmed = String(key || "").trim();
  if (!trimmed) return "";
  if (/^ri-[a-z0-9][a-z0-9-]*$/.test(trimmed)) return trimmed;
  return LEGACY_ICON_TO_REMIX[trimmed] || trimmed;
}
