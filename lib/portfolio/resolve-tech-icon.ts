export function resolveTechIconName(name: string): string {
  const n = String(name || "").toLowerCase().trim();
  if (!n) return "siCode";
  for (const [pattern, icon] of ICON_RULES) {
    if (pattern.test(n)) return icon;
  }
  if (n === "sql") return "siSql";
  return "siCode";
}
